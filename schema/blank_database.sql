-- Empty schema for a new 1D Navier-Stokes experiment database.
-- Keep this aligned with the tables read and written by the application.

PRAGMA foreign_keys = ON;

CREATE TABLE model_controls (
    "Parameter" TEXT NOT NULL,
    Setting ANY
);

CREATE TABLE experiments (
    NAME TEXT NOT NULL,
    LOW_REF_LEFT INT,
    LOW_REF_RIGHT INT,
    HIGH_REF_LEFT INT,
    HIGH_REF_RIGHT INT,
    PARAMETERS_TO_SOLVE_FOR TEXT,
    DEFAULT_NORMALIZATION TEXT,
    REACTIONS TEXT,
    SPECIES TEXT,
    ENTRANCE_FLOWRATE ANY,
    SPECIE_INLET_CONC_UNITS ANY,
    SPECIE_MODEL_CONC_UNITS ANY,
    LEFT_EDGE NUMERIC,
    WIDTH NUMERIC,
    CHANNEL_WIDTH REAL NOT NULL DEFAULT 5e-4
        CHECK(typeof(CHANNEL_WIDTH) IN ('real','integer') AND CHANNEL_WIDTH > 0 AND CHANNEL_WIDTH <= 1.7976931348623157e308),
    CHANNEL_HEIGHT REAL NOT NULL DEFAULT 4e-5
        CHECK(typeof(CHANNEL_HEIGHT) IN ('real','integer') AND CHANNEL_HEIGHT > 0 AND CHANNEL_HEIGHT <= 1.7976931348623157e308),
    CHANNEL_LENGTH REAL NOT NULL DEFAULT 0.025
        CHECK(typeof(CHANNEL_LENGTH) IN ('real','integer') AND CHANNEL_LENGTH > 0 AND CHANNEL_LENGTH <= 1.7976931348623157e308),
    CONSTRAINT EXPERIMENTS_PK PRIMARY KEY (NAME)
);

CREATE TABLE species (
    SPECIES_NAME TEXT NOT NULL,
    SPECIES_TYPE TEXT,
    DIFFUSION_RATE NUMERIC,
    PARTICLE_DIAMETER NUMERIC,
    QE DOUBLE,
    PARTICLE_DENSITY DOUBLE,
    MOLECULAR_WEIGHT DOUBLE,
    CONSTRAINT species_pk PRIMARY KEY (SPECIES_NAME)
);

CREATE TABLE reactions (
    REACTION_NAME TEXT NOT NULL,
    SPECIES ANY,
    COEFFICIENTS ANY,
    Ks ANY,
    EXPONENTS ANY,
    SPECIE_UNITS
);

CREATE TABLE alglib_input (
    VARIABLE TEXT,
    "LOWER BOUND" DOUBLE,
    "UPPER BOUND" DOUBLE,
    "INITIAL VALUE" TEXT,
    "SCALE" TEXT
);

CREATE TABLE raw_profile (
    NAME TEXT NOT NULL,
    WT_PERCENT DOUBLE NOT NULL,
    CHANNEL_LEFT_EDGE INT,
    CHANNEL_RIGHT_EDGE INT,
    INTENSITY_ARRAY TEXT,
    ENTRANCE_CONC ANY,
    OMIT ANY,
    INDEPENDENT_PARAMETERS_TO_SOLVE_FOR TEXT,
    LEFT_EDGE NUMERIC,
    WIDTH NUMERIC,
    ENTRANCE_CONC_UNITS TEXT,
    CONSTRAINT RAW_PROFILE_PK PRIMARY KEY (NAME, WT_PERCENT)
);

CREATE TABLE raw_profile_entrance_concentrations (
    NAME TEXT NOT NULL,
    WT_PERCENT TEXT NOT NULL,
    ENTRANCE_NUMBER INTEGER NOT NULL
        CHECK(typeof(ENTRANCE_NUMBER)='integer' AND ENTRANCE_NUMBER >= 1),
    SPECIES_NAME TEXT NOT NULL,
    CONCENTRATION ANY NOT NULL
        CHECK(
            (typeof(CONCENTRATION) IN ('real','integer') AND CONCENTRATION >= 0 AND CONCENTRATION <= 1.7976931348623157e308)
            OR
            (typeof(CONCENTRATION)='text' AND instr(CONCENTRATION, '#') > 0
                AND length(CONCENTRATION) > instr(CONCENTRATION, '#')
                AND instr(CONCENTRATION, ' ') = 0
                AND instr(CONCENTRATION, char(9)) = 0
                AND instr(CONCENTRATION, char(10)) = 0
                AND instr(CONCENTRATION, char(13)) = 0)
        ),
    UNITS TEXT,
    PRIMARY KEY (NAME, WT_PERCENT, ENTRANCE_NUMBER, SPECIES_NAME)
);

CREATE TABLE profile_calculations (
    RUN_AT_UTC_US INTEGER NOT NULL PRIMARY KEY,
    ALL_EXP_FITTED TEXT,
    PARAMETERS_SOLVED_FOR TEXT,
    REACTIONS_ENABLED TEXT,
    SCATTER_METHOD TEXT,
    X_RESOLUTION INTEGER,
    Z_RESOLUTION INTEGER
);

CREATE TABLE profile_records (
    RUN_AT_UTC_US INTEGER NOT NULL,
    EXPERIMENT_NAME TEXT NOT NULL,
    WT_PERCENT TEXT NOT NULL,
    EXP_DA NUMERIC,
    MODEL_DA NUMERIC,
    EXP_INTEGRAL NUMERIC,
    MODEL_INTEGRAL NUMERIC,
    PRIMARY KEY (RUN_AT_UTC_US, EXPERIMENT_NAME, WT_PERCENT),
    FOREIGN KEY (RUN_AT_UTC_US) REFERENCES profile_calculations(RUN_AT_UTC_US) ON DELETE CASCADE
);
CREATE INDEX profile_records_profile_run ON profile_records(EXPERIMENT_NAME, WT_PERCENT, RUN_AT_UTC_US);

CREATE TABLE profile_record_parameters (
    RUN_AT_UTC_US INTEGER NOT NULL,
    EXPERIMENT_NAME TEXT NOT NULL DEFAULT '',
    WT_PERCENT TEXT NOT NULL DEFAULT '',
    PARAMETER TEXT NOT NULL,
    VALUE NUMERIC,
    UNITS TEXT,
    SOURCE TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (RUN_AT_UTC_US, EXPERIMENT_NAME, WT_PERCENT, PARAMETER, SOURCE),
    FOREIGN KEY (RUN_AT_UTC_US) REFERENCES profile_calculations(RUN_AT_UTC_US) ON DELETE CASCADE
);

CREATE TABLE profile_record_samples (
    RUN_AT_UTC_US INTEGER NOT NULL,
    EXPERIMENT_NAME TEXT NOT NULL,
    WT_PERCENT TEXT NOT NULL,
    X NUMERIC NOT NULL,
    Free_Dye NUMERIC,
    Bound_Dye NUMERIC,
    Total_Dye NUMERIC,
    Unbound_Beads NUMERIC,
    Bound_Beads NUMERIC,
    Total_Beads NUMERIC,
    Experimental_Derivative NUMERIC,
    Numeric_Derivative NUMERIC,
    Experimental NUMERIC,
    "Numeric" NUMERIC,
    Error NUMERIC,
    Experimental_Difference NUMERIC,
    Numeric_Difference NUMERIC,
    PRIMARY KEY (RUN_AT_UTC_US, EXPERIMENT_NAME, WT_PERCENT, X),
    FOREIGN KEY (RUN_AT_UTC_US, EXPERIMENT_NAME, WT_PERCENT)
        REFERENCES profile_records(RUN_AT_UTC_US, EXPERIMENT_NAME, WT_PERCENT) ON DELETE CASCADE
);

CREATE INDEX profile_record_samples_lookup
    ON profile_record_samples(EXPERIMENT_NAME, WT_PERCENT, RUN_AT_UTC_US, X);

PRAGMA user_version = 5;

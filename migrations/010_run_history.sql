-- Persist a per-run snapshot of model controls and reaction/species values.
BEGIN IMMEDIATE;
CREATE TABLE run_history (
    ID INTEGER PRIMARY KEY,
    COMPLETED_AT_UTC TEXT NOT NULL,
    EXPERIMENTS TEXT,
    STATUS TEXT NOT NULL,
    RESIDUAL_EVALUATIONS INTEGER,
    ITERATIONS INTEGER,
    RESIDUAL_SUM REAL
);
CREATE TABLE run_history_values (
    RUN_ID INTEGER NOT NULL REFERENCES run_history(ID) ON DELETE CASCADE,
    CATEGORY TEXT NOT NULL,
    ITEM TEXT NOT NULL,
    FIELD TEXT NOT NULL,
    VALUE TEXT,
    PRIMARY KEY (RUN_ID, CATEGORY, ITEM, FIELD)
);
PRAGMA user_version = 6;
COMMIT;
